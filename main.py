    def split_text_for_pdf(self, text, max_length):
        """Разбиваем текст на части для отображения в PDF"""
        if len(text) <= max_length:
            return [text]
        
        words = text.split(' ')
        lines = []
        current_line = ""
        
        for word in words:
            if len(current_line + " " + word) <= max_length:
                if current_line:
                    current_line += " " + word
                else:
                    current_line = word
            else:
                if current_line:
                    lines.append(current_line)
                current_line = word
        
        if current_line:
            lines.append(current_line)
        
        return lines
    
    def find_similar_profiles(self):
        """Поиск похожих профилей по схожести"""
        selected_items = self.profiles_list.selectedItems()
        if not selected_items:
            QMessageBox.warning(self, "Предупреждение", "Пожалуйста, выберите профиль для поиска схожих")
            return
        
        selected_profile_name = selected_items[0].text()
        
        # Находим профиль по имени
        selected_profile = None
        for p in self.profiles:
            if p["name"] == selected_profile_name:
                selected_profile = p
                break
        
        if not selected_profile:
            return
        
        # Вычисляем схожесть с другими профилями
        similarities = []
        for profile in self.profiles:
            if profile["name"] != selected_profile_name:  # Не сравниваем профиль с самим собой
                similarity = self.calculate_similarity(selected_profile, profile)
                if similarity >= SIMILARITY_THRESHOLD:
                    similarities.append((profile, similarity))
        
        # Сортируем по схожести (в убывающем порядке)
        similarities.sort(key=lambda x: x[1], reverse=True)
        
        if not similarities:
            QMessageBox.information(self, "Результат", "Не найдено похожих профилей.")
            return
        
        # Показываем результаты
        result_text = f"Похожие профили для '{selected_profile['name']}':\n\n"
        for profile, similarity in similarities:
            result_text += f"{profile['name']} (схожесть: {similarity:.2f})\n"
        
        msg_box = QMessageBox()
        msg_box.setWindowTitle("Похожие профили")
        msg_box.setText(result_text)
        msg_box.exec()
    
    def calculate_similarity(self, profile1, profile2):
        """Вычисление схожести между двумя профилями"""
        # Объединяем все элементы профилей для вычисления схожести
        all_items1 = (
            profile1['name'].lower().split() + 
            profile1['description'].lower().split() + 
            [trait.lower() for trait in profile1['traits']] + 
            [behavior.lower() for behavior in profile1['behaviors']] +
            [temp.lower() for temp in profile1.get('temperament', [])] +
            [sex_beh.lower() for sex_beh in profile1.get('sexual_behavior', [])] +
            [clothing.lower() for clothing in profile1.get('clothing_preferences', [])]
        )
        
        all_items2 = (
            profile2['name'].lower().split() + 
            profile2['description'].lower().split() + 
            [trait.lower() for trait in profile2['traits']] + 
            [behavior.lower() for behavior in profile2['behaviors']] +
            [temp.lower() for temp in profile2.get('temperament', [])] +
            [sex_beh.lower() for sex_beh in profile2.get('sexual_behavior', [])] +
            [clothing.lower() for clothing in profile2.get('clothing_preferences', [])]
        )
        
        # Находим общие элементы
        set1 = set(all_items1)
        set2 = set(all_items2)
        
        # Вычисляем коэффициент Жаккара
        intersection = set1.intersection(set2)
        union = set1.union(set2)
        
        if len(union) == 0:
            return 0.0
        
        return len(intersection) / len(union)
    
