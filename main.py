        if not file_path:  # Если пользователь отменил операцию
            return
        
        # Регистрируем шрифт с поддержкой кириллицы
        pdfmetrics.registerFont(TTFont('DejaVuSans', 'dejavu-fonts-ttf-2.37/ttf/DejaVuSans.ttf'))
        
